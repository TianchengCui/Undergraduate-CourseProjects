package core;
import edu.princeton.cs.algs4.In;
import edu.princeton.cs.algs4.Out;
import edu.princeton.cs.algs4.StdDraw;
import tileengine.TERenderer;
import tileengine.TETile;
import tileengine.Tileset;

import java.util.Random;

public class Engine {
    private static final int WIDTH = 70;
    private static final int HEIGHT = 35;
    private static final TETile PATH_TILE = Tileset.SAND;

    private GameMode mode;
    private StringBuilder seedInput;
    private World currWorld;
    private TETile[][] world;
    private TERenderer ter;
    private int playerX;
    private int playerY;
    private StringBuilder history;
    private boolean isQ;
    private long currSeed;
    private Random randomStartPlace;

    private TETile[][] mainWorld;
    private int mainPlayerX;
    private int mainPlayerY;

    private Encounter encounter;
    private boolean gameOver;
    private boolean gameWon;
    private int playerMovesInEncounter;

    private java.util.List<Position> currentPath;
    private java.util.List<TETile> currentPathOriginalTiles;
    private Position currentPathTarget;
    private boolean mouseWasPressed;

    public Engine() {
        mode = GameMode.MAIN_MENU;
        isQ = false;
        gameOver = false;
        gameWon = false;
        playerMovesInEncounter = 0;
        mouseWasPressed = false;
        seedInput = new StringBuilder();
        history = new StringBuilder();
        ter = new TERenderer();
        encounter = new Encounter();
    }

    public void start() {
        ter.initialize(WIDTH, HEIGHT);
        drawMainMenu();
        while (true) {
            if (StdDraw.hasNextKeyTyped()) {
                char c = StdDraw.nextKeyTyped();
                keyHandler(c);
            }

            if (gameOver || gameWon) {
                StdDraw.pause(20);
                continue;
            }

            if (mode == GameMode.IN_GAME) {
                handleMouseClick();
            }

            if (mode == GameMode.ENCOUNTER && world != null && encounter.shouldMoveMonster()) {
                boolean caught = encounter.moveMonster(world, WIDTH, HEIGHT, playerX, playerY);
                if (caught) {
                    triggerGameOver();
                }
            }

            if (gameOver || gameWon) {
                StdDraw.pause(20);
                continue;
            }

            if ((mode == GameMode.IN_GAME || mode == GameMode.ENCOUNTER) && world != null) {
                ter.drawTiles(world);
                if (mode == GameMode.IN_GAME) {
                    drawHUD();
                } else {
                    drawEncounterHUD();
                }
                StdDraw.show();
            }
            StdDraw.pause(20); // Generated by LLM
        }
    }

    private void keyHandler(char c) {
        c = Character.toUpperCase(c);

        if (gameOver || gameWon) {
            if (c == 'Q') {
                System.exit(0);
            }
            return;
        }

        if (mode == GameMode.MAIN_MENU) {
            mainMenuHandler(c);
        } else if (mode == GameMode.SEED_INPUT) {
            seedHandler(c);
        } else if (mode == GameMode.IN_GAME) {
            gameKeyHandler(c);
        } else if (mode == GameMode.ENCOUNTER) {
            encounterKeyHandler(c);
        }
    }

    private void mainMenuHandler(char c) {
        if (c == 'N') {
            mode = GameMode.SEED_INPUT;
            seedInput.setLength(0);
            history.setLength(0);
            history.append('N');
            encounter.reset();
            clearActivePath();
            gameOver = false;
            gameWon = false;
            drawSeedInputScreen();
        }
        if (c == 'Q') {
            System.exit(0);
        }
        if (c == 'L') {
            String saved = loadGame();
            replay(saved);
        }

    }

    private void avatarPlace() {
        while (true) {
            int x = randomStartPlace.nextInt(WIDTH);
            int y = randomStartPlace.nextInt(HEIGHT);
            if (world[x][y] == Tileset.FLOOR) {
                playerX = x;
                playerY = y;
                world[x][y] = Tileset.AVATAR;
                return;
            }
        }

    }

    private void seedHandler(char c) {
        if (Character.isDigit(c)) {
            seedInput.append(c);
            history.append(c);
            drawSeedInputScreen();
        } else if (Character.toUpperCase(c) == 'S') {
            history.append('S');
            long seed = Long.parseLong(seedInput.toString());
            currSeed = seed;
            randomStartPlace = new Random(currSeed);
            currWorld = new World(WIDTH, HEIGHT, seed);
            world = currWorld.generateWorld();
            encounter.reset();
            clearActivePath();
            gameOver = false;
            gameWon = false;
            avatarPlace();
            encounter.placeEncounterEntrances(world, WIDTH, HEIGHT, playerX, playerY, currSeed);
            mode = GameMode.IN_GAME;
            ter.drawTiles(world);
            StdDraw.show();
        }
    }

    private void gameKeyHandler(char c) {
        c = Character.toUpperCase(c);
        if (isQ) {
            if (c == 'Q') {
                saveGame();
                System.exit(0);
            }
            isQ = false;
            return;
        }
        if (c == ':') {
            isQ = true;
            return;
        }

        boolean moved = false;

        if (c == 'W') {
            clearActivePath();
            moved = motion(0, 1);
        } else if (c == 'S') {
            clearActivePath();
            moved = motion(0, -1);
        } else if (c == 'A') {
            clearActivePath();
            moved = motion(-1, 0);
        } else if (c == 'D') {
            clearActivePath();
            moved = motion(1, 0);
        }

        if (moved && (c == 'W' || c == 'A' || c == 'S' || c == 'D')) {
            history.append(c);
        }
    }

    private boolean motion(int x, int y) {
        int newX = playerX + x;
        int newY = playerY + y;
        if ((newX < 0) || newX >= WIDTH || newY < 0 || newY >= HEIGHT) {
            return false;
        }

        int encounterId = encounter.encounterAt(newX, newY);
        if (encounterId != -1) {
            startEncounter(encounterId);
            return true;
        }

        if (world[newX][newY] != Tileset.FLOOR) {
            return false;
        }

        world[playerX][playerY] = Tileset.FLOOR;
        playerX = newX;
        playerY = newY;
        world[playerX][playerY] = Tileset.AVATAR;
        ter.drawTiles(world);
        StdDraw.show();

        return true;
    }

    private void startEncounter(int encounterId) {
        clearActivePath();

        mainWorld = world;
        mainPlayerX = playerX;
        mainPlayerY = playerY;

        encounter.markEncounterUsed(mainWorld, encounterId);

        world = encounter.createEncounterWorld(encounterId, WIDTH, HEIGHT);

        playerX = WIDTH / 2;
        playerY = HEIGHT / 2;
        world[playerX][playerY] = Tileset.AVATAR;

        encounter.placeMonster(world, WIDTH, HEIGHT, playerX, playerY, currSeed, encounterId);

        mode = GameMode.ENCOUNTER;
        isQ = false;
        playerMovesInEncounter = 0;

        ter.drawTiles(world);
        StdDraw.show();
    }

    private void encounterKeyHandler(char c) {
        c = Character.toUpperCase(c);

        boolean moved = false;

        if (c == 'W') {
            moved = encounterMotion(0, 1);
        } else if (c == 'S') {
            moved = encounterMotion(0, -1);
        } else if (c == 'A') {
            moved = encounterMotion(-1, 0);
        } else if (c == 'D') {
            moved = encounterMotion(1, 0);
        }

        if (moved && (c == 'W' || c == 'A' || c == 'S' || c == 'D')) {
            history.append(c);
        }
    }

    private boolean encounterMotion(int x, int y) {
        int newX = playerX + x;
        int newY = playerY + y;

        if ((newX < 0) || newX >= WIDTH || newY < 0 || newY >= HEIGHT) {
            return false;
        }

        if (encounter.isMonster(world[newX][newY])) {
            triggerGameOver();
            return true;
        }

        if (world[newX][newY] != Tileset.FLOOR && !encounter.isCoin(world[newX][newY])) {
            return false;
        }

        if (encounter.isCoin(world[newX][newY])) {
            encounter.collectCoin();
        }

        world[playerX][playerY] = Tileset.FLOOR;
        playerX = newX;
        playerY = newY;
        world[playerX][playerY] = Tileset.AVATAR;

        if (encounter.roomCleared()) {
            endEncounter();
            return true;
        }

        playerMovesInEncounter++;

        if (playerMovesInEncounter % 2 == 0) {
            boolean caught = encounter.moveMonster(world, WIDTH, HEIGHT, playerX, playerY);
            if (caught) {
                triggerGameOver();
                return true;
            }
        }

        if (!gameOver && !gameWon) {
            ter.drawTiles(world);
            StdDraw.show();
        }

        return true;
    }

    private void handleMouseClick() {
        boolean mousePressed = StdDraw.isMousePressed();

        if (!mousePressed) {
            mouseWasPressed = false;
            return;
        }

        if (mouseWasPressed) {
            return;
        }

        mouseWasPressed = true;

        int targetX = (int) StdDraw.mouseX();
        int targetY = (int) StdDraw.mouseY();

        if (targetX < 0 || targetX >= WIDTH || targetY < 0 || targetY >= HEIGHT) {
            return;
        }

        if (currentPathTarget != null
                && currentPathTarget.x == targetX
                && currentPathTarget.y == targetY
                && currentPath != null) {
            animateCurrentPath();
            return;
        }

        drawNewPathTo(targetX, targetY);
    }

    private void drawNewPathTo(int targetX, int targetY) {
        clearActivePath();

        java.util.List<Position> path = PathFinder.shortestPath(world, WIDTH, HEIGHT,
                playerX, playerY, targetX, targetY);

        if (path == null || path.size() <= 1) {
            return;
        }

        currentPath = path;
        currentPathOriginalTiles = new java.util.ArrayList<>();
        currentPathTarget = path.get(path.size() - 1);

        for (int i = 1; i < currentPath.size(); i++) {
            Position p = currentPath.get(i);
            currentPathOriginalTiles.add(world[p.x][p.y]);
            world[p.x][p.y] = PATH_TILE;
        }

        ter.drawTiles(world);
        drawHUD();
        StdDraw.show();
    }

    private void animateCurrentPath() {
        if (currentPath == null || currentPathOriginalTiles == null) {
            return;
        }

        java.util.List<Position> pathToMove = currentPath;
        java.util.List<TETile> originalTiles = currentPathOriginalTiles;

        for (int i = 1; i < pathToMove.size(); i++) {
            if (mode != GameMode.IN_GAME || gameOver || gameWon) {
                return;
            }

            Position next = pathToMove.get(i);
            int dx = next.x - playerX;
            int dy = next.y - playerY;

            if (Math.abs(dx) + Math.abs(dy) != 1) {
                clearActivePath();
                return;
            }

            TETile originalNextTile = originalTiles.get(i - 1);

            if (originalNextTile == Tileset.LOCKED_DOOR) {
                restorePathExceptAvatar(pathToMove, originalTiles);
                currentPath = null;
                currentPathOriginalTiles = null;
                currentPathTarget = null;

                int encounterId = encounter.encounterAt(next.x, next.y);
                if (encounterId != -1) {
                    history.append(directionChar(dx, dy));
                    startEncounter(encounterId);
                }
                return;
            }

            world[playerX][playerY] = Tileset.FLOOR;
            playerX = next.x;
            playerY = next.y;
            world[playerX][playerY] = Tileset.AVATAR;

            history.append(directionChar(dx, dy));

            ter.drawTiles(world);
            drawHUD();
            StdDraw.show();
            StdDraw.pause(80);
        }

        currentPath = null;
        currentPathOriginalTiles = null;
        currentPathTarget = null;
    }

    private void restorePathExceptAvatar(java.util.List<Position> path,
                                         java.util.List<TETile> originalTiles) {
        for (int i = 1; i < path.size(); i++) {
            Position p = path.get(i);

            if (p.x == playerX && p.y == playerY) {
                continue;
            }

            world[p.x][p.y] = originalTiles.get(i - 1);
        }
    }

    private char directionChar(int dx, int dy) {
        if (dx == 1) {
            return 'D';
        } else if (dx == -1) {
            return 'A';
        } else if (dy == 1) {
            return 'W';
        } else {
            return 'S';
        }
    }

    private void clearActivePath() {
        if (currentPath != null && currentPathOriginalTiles != null) {
            for (int i = 1; i < currentPath.size(); i++) {
                Position p = currentPath.get(i);
                TETile originalTile = currentPathOriginalTiles.get(i - 1);
                world[p.x][p.y] = originalTile;
            }
        }

        currentPath = null;
        currentPathOriginalTiles = null;
        currentPathTarget = null;
    }

    private void triggerGameOver() {
        clearActivePath();
        gameOver = true;
        drawGameOverScreen();
        StdDraw.show();
    }

    private void triggerGameWin() {
        clearActivePath();
        gameWon = true;
        drawGameWinScreen();
        StdDraw.show();
    }

    private void endEncounter() {
        world = mainWorld;
        playerX = mainPlayerX;
        playerY = mainPlayerY;
        mode = GameMode.IN_GAME;

        if (encounter.hasWon()) {
            triggerGameWin();
            return;
        }

        ter.drawTiles(world);
        StdDraw.show();
    }

    private void drawMainMenu() {
        StdDraw.clear(StdDraw.BLACK);
        StdDraw.setPenColor(StdDraw.WHITE);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.75, "BYOW");
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.55, "N - New Game");
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.48, "L - Load Game");
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.41, "Q - Quit");
        StdDraw.show();
    }

    private void drawSeedInputScreen() {
        StdDraw.clear(StdDraw.BLACK);
        StdDraw.setPenColor(StdDraw.WHITE);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.75, "Enter Your Seed:");
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.60, seedInput.toString());
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.45, "Press S to Start");
        StdDraw.show();
    }

    private void saveGame() {
        clearActivePath();

        Out out = new Out("save.txt");
        out.println(history.toString());
        out.close();
    }

    private String loadGame() {
        In in = new In("save.txt");
        if (!in.exists()) {
            return "";
        }
        String saved = in.readLine();
        in.close();
        return saved;
    }

    private void replay(String history) {
        for (int i = 0; i < history.length(); i++) {
            char c = history.charAt(i);
            keyHandler(c);
        }
    }

    private void drawHUD() {
        int mouseX = (int) StdDraw.mouseX();
        int mouseY = (int) StdDraw.mouseY();
        if (mouseY <= 0 || mouseY >= HEIGHT || mouseX <= 0 || mouseX >= WIDTH) {
            return;
        }
        TETile tile = world[mouseX][mouseY];
        String tileInfo = tile.description(); // This line is Generated BY LLM
        StdDraw.setPenColor(StdDraw.GREEN);
        StdDraw.textLeft(15, HEIGHT - 1, "Tile: " + tileInfo);
        StdDraw.textLeft(1, HEIGHT - 1, "Current Seed: " + currSeed);
        StdDraw.textLeft(35, HEIGHT - 1,
                "Coins: " + encounter.getTotalCoins() + " / " + encounter.getCoinsToWin());
        StdDraw.textRight(WIDTH - 1, HEIGHT - 1, "Press :Q to Save & Quit");
    }

    private void drawEncounterHUD() {
        StdDraw.setPenColor(StdDraw.YELLOW);
        StdDraw.textLeft(1, HEIGHT - 1, "Encounter " + (encounter.getCurrentEncounterId() + 1));
        StdDraw.textLeft(18, HEIGHT - 1, "Room Coins Left: " + encounter.getCoinsLeft());
        StdDraw.textLeft(38, HEIGHT - 1,
                "Total: " + encounter.getTotalCoins() + " / " + encounter.getCoinsToWin());
        StdDraw.textRight(WIDTH - 1, HEIGHT - 1, "Collect all coins to return");
    }

    private void drawGameOverScreen() {
        StdDraw.clear(StdDraw.BLACK);
        StdDraw.setPenColor(StdDraw.RED);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.60, "GAME OVER");
        StdDraw.setPenColor(StdDraw.WHITE);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.45, "You were caught by the monster");
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.35, "Press Q to quit");
    }

    private void drawGameWinScreen() {
        StdDraw.clear(StdDraw.BLACK);
        StdDraw.setPenColor(StdDraw.GREEN);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.62, "YOU WIN!");
        StdDraw.setPenColor(StdDraw.WHITE);
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.48,
                "Total Coins: " + encounter.getTotalCoins() + " / " + encounter.getCoinsToWin());
        StdDraw.text(WIDTH / 2.0, HEIGHT * 0.36, "Press Q to quit");
    }
}
